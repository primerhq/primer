"""Chunk, embed, and index user-collection documents into the vector store.

When a Document is created or updated through the REST CRUD routes, its
stored text (``meta['text']`` or ``meta['content']``) is split into
chunks, each chunk is embedded with the parent collection's configured
embedder, and the resulting :class:`EmbeddingRecord` rows are upserted
into the collection's vector store. This is what makes per-collection
search and the "view chunks of a document" UI return results.

System (``system=True``) collections are skipped here: their content is
regenerated by the platform (the system collection), not hand-ingested.

Indexing is best-effort. If the embedder or vector store fails (for
example a missing API key), the failure is logged and swallowed so the
Document storage row still persists; search simply will not see the
document until indexing succeeds on a later update.
"""

from __future__ import annotations

import asyncio
import logging
import re as _re
import time
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager

from primer.int.document_content import DocumentContentStore
from primer.model.chat import TextPart
from primer.model.collection import Collection, Document
from primer.model.except_ import ConflictError, DimensionMismatchError, PrimerError
from primer.model.vector import EmbeddingRecord

logger = logging.getLogger(__name__)

# Target chunk size in characters. Paragraph-aware: paragraphs are packed
# up to this size, and any single paragraph longer than the hard cap is
# split on character boundaries so one huge block still embeds.

# Number of chunks embedded per embedder call. Mirrors
# the previous ingester's default so user-collection ingestion and
# the system collection's indexing batch identically.
_EMBED_BATCH_SIZE = 32

# The width of an embedder's vectors, per (collection, embedder, model): every write to a collection used to spend an embedder call
# asking. The key names the embedder, so a collection moved to another one asks again; the ttl bounds a provider whose width was edited
# in place (M5).
_DIMENSIONS_TTL_SECONDS = 600.0
_dimensions: dict[tuple[str, str, str], tuple[float, int]] = {}


def forget_dimensions(collection_id: str | None = None) -> None:
    """Drop the cached embedder widths (of one collection, or all): call when a collection is recreated or its embedder is edited."""
    if collection_id is None:
        _dimensions.clear()
        return
    for key in [k for k in _dimensions if k[0] == collection_id]:
        del _dimensions[key]


def _dimensions_key(collection: Collection) -> tuple[str, str, str]:
    embedder = collection.search.embedder  # type: ignore[union-attr]
    return (collection.id, embedder.provider_id, embedder.model)


# One lock per (collection, document) in this process (KN-9): the read-embed-replace of an index write and the delete of a removal are not atomic
# on the vector store, so two indexers of one document (or an index and a delete) could interleave and leave the OLDER body's chunks, or chunks of a
# document that is gone. Process-local: another process is a peer writer the post-embed re-read still catches.
_doc_locks: dict[tuple[str, str], list] = {}


@asynccontextmanager
async def _document_lock(collection_id: str, document_id: str) -> AsyncIterator[None]:
    entry = _doc_locks.setdefault((collection_id, document_id), [asyncio.Lock(), 0])
    entry[1] += 1
    try:
        async with entry[0]:
            yield
    finally:
        entry[1] -= 1
        if entry[1] == 0:
            _doc_locks.pop((collection_id, document_id), None)


async def _put_all(store, records) -> None:
    """One write when the store offers it (``put_many``), else one ``put`` per record."""
    put_many = getattr(store, "put_many", None)
    if put_many is not None:
        await put_many(records)
        return
    for record in records:
        await store.put(record)


def embedder_fingerprint(collection: Collection) -> str:
    """Who embedded a chunk: the embedding provider and model of the collection. The documents are embedded as plain passages with no
    per-collection prompt setting, so those two are all there is to tell one embedding from another. Stored in each chunk's meta."""
    embedder = collection.search.embedder  # type: ignore[union-attr]
    return f"{embedder.provider_id}|{embedder.model}"


async def _stored_chunk_texts(
    store, collection_id: str, document_id: str | None = None,
) -> dict[str, dict[str, tuple[str, str | None]]]:
    """``{document_id: {chunk_id: (text, embedder fingerprint)}}`` of what the index holds, without decoding vectors where the store can avoid
    it. A chunk with no fingerprint (written before there was one) carries ``None``. A collection the store does not know reads as empty."""
    out: dict[str, dict[str, tuple[str, str | None]]] = {}
    try:
        lister = getattr(store, "list_chunk_texts", None)
        if lister is not None:
            rows = await lister(collection_id, document_id)
        elif document_id is not None:
            rows = [(r.document_id, r.chunk_id, r.text, (r.meta or {}).get("embedder")) for r in await store.get(collection_id, document_id)]
        else:
            rows = [(r.document_id, r.chunk_id, r.text, (r.meta or {}).get("embedder")) for r in await store.search_by_meta(collection_id, {})]
    except Exception:  # noqa: BLE001 - absent index reads as empty
        return {}
    for row in rows:
        doc_id, chunk_id, text = row[:3]
        out.setdefault(doc_id, {})[chunk_id] = (text, row[3] if len(row) > 3 else None)
    return out


def _is_current(stored: dict[str, tuple[str, str | None]] | None, chunks: list[str], fingerprint: str) -> bool:
    """Whether the stored chunks are exactly these texts, embedded by this embedder. A chunk with no fingerprint is NOT current: it is
    re-embedded once, the safe side when the model it came from is unknown."""
    return stored == {str(i): (c, fingerprint) for i, c in enumerate(chunks)}


def _parse_stored_dim(conflict_message: str, *, fallback: int) -> int:
    """Extract the stored vector dimension from a ConflictError message.

    All backends embed the stored dimension as ``dimensions=<N>`` in their
    ConflictError text. Returns ``fallback`` when the pattern is absent.
    """
    # Match the FIRST "dimensions=<N>" occurrence -- that is the stored dim.
    m = _re.search(r"dimensions=(\d+)", conflict_message)
    if m:
        return int(m.group(1))
    return fallback


async def probe_dimensions(*, collection: Collection, provider_registry) -> int:
    """Ask the collection's embedder how wide its vectors are.

    One cheap call. Split out so a backfill can do it once for the whole
    collection instead of once per document: every document in a
    collection shares one embedder, so the answer cannot differ between
    them, and on a collection the size of the system map the repeated
    probe doubled the number of embedder round-trips the pass made.
    """
    if collection.search is None:  # pragma: no cover -- callers check first
        raise PrimerError(f"collection {collection.id!r} has no search config")
    embedder = await provider_registry.get_embedder(
        collection.search.embedder.provider_id
    )
    response = await embedder.embed(
        model=collection.search.embedder.model,
        inputs=[TextPart(text="dimensionality probe")],
    )
    if not response.embeddings:
        raise PrimerError(
            f"embedder returned no embedding for dimensionality probe "
            f"(collection {collection.id!r})"
        )
    return len(response.embeddings[0].vector)


async def _refuse_unless_an_owner_may_use(storage_provider, collection: Collection) -> None:
    """Fail closed when no owner of ``collection`` may use the providers its search names (security review of P4, finding 2): the enable
    check covers the owner who turned search on, and this keeps a row that bypassed it from spending them. No storage: no check (tests)."""
    from primer.knowledge.search_use import owners_may_use

    if storage_provider is not None and not await owners_may_use(storage_provider, collection):
        raise PrimerError(
            f"indexing refused: no owner of collection {collection.id!r} may use the search providers it names; "
            "an admin can grant their use, then re-enable search"
        )


_REINDEX_ATTEMPTS = 5


async def index_document(
    *,
    document: Document,
    collection: Collection,
    provider_registry,
    semantic_search_registry,
    content_store: DocumentContentStore,
    dimensions: int | None = None,
    storage_provider=None,
    force: bool = False,
) -> int:
    """Chunk, embed and upsert ``document`` (see :func:`_index_document_once`), serialised per document in this process and re-run when the body
    changed while it was being embedded, so the index ends up holding the LATEST body whichever indexers raced (KN-9)."""
    if collection.search is None:
        return 0
    async with _document_lock(collection.id, document.id):
        count = 0
        for _ in range(_REINDEX_ATTEMPTS):
            count, again = await _index_document_once(
                document=document, collection=collection, provider_registry=provider_registry,
                semantic_search_registry=semantic_search_registry, content_store=content_store, dimensions=dimensions,
                storage_provider=storage_provider, force=force,
            )
            if not again:
                break
        return count


async def _index_document_once(
    *,
    document: Document,
    collection: Collection,
    provider_registry,
    semantic_search_registry,
    content_store: DocumentContentStore,
    dimensions: int | None = None,
    storage_provider=None,
    force: bool = False,
) -> tuple[int, bool]:
    """Chunk, embed, and upsert ``document`` into its collection's vector
    store. Returns the number of chunks indexed. Re-indexing embeds the new
    chunks FIRST and only then replaces the document's existing chunks, so a
    failed re-embed leaves the prior index intact (the document stays
    searchable) rather than wiping it.

    The indexable body is read from the content store keyed by the stable
    document id. Bodies live there now, not in ``meta``. For a not-yet-
    migrated document with no content row, this falls back to the legacy
    ``meta['text']`` / ``meta['content']`` read so nothing breaks in transit.

    A collection with no search config is skipped (returns 0). System
    collections are NOT: the system collection is precisely what
    /v1/internal_collections/bootstrap vectorises, so skipping them made
    that toggle a no-op that still reported success (state "ready" with
    zero documents indexed, and no vector-store collection ever created).
    The guard dates from when "system" meant the four _internal_* rows a
    separate ingest path owned. Search being unset is the real signal now.

    ``dimensions`` skips the per-document probe when the caller already
    knows the embedder's width (see :func:`probe_dimensions`).

    A document whose stored chunks are the same texts, embedded by the same embedder (provider and model), is not re-embedded. ``force``
    (an explicit reindex) never skips.

    On embedder/store failure it raises; the caller treats indexing as
    best-effort and swallows it.
    """
    if collection.search is None:
        return 0, False
    await _refuse_unless_an_owner_may_use(storage_provider, collection)
    cfg = collection.search

    body = await content_store.get(document.id)
    text = "" if body is None else body
    from primer.knowledge.splitter import split_text

    chunks = split_text(
        text,
        max_chars=cfg.chunking.max_chars,
        overlap=cfg.chunking.overlap,
    )

    embedder = await provider_registry.get_embedder(
        cfg.embedder.provider_id
    )
    store = await semantic_search_registry.get_store(
        cfg.vector_store_provider_id
    )

    # Probe the embedder's output dimensionality with a single cheap call
    # BEFORE embedding all chunks. This lets us detect a mismatch between
    # the embedder and the vector store's stored collection dimension early
    # -- without wasting a full embedding pass on a batch that cannot be
    # stored. We register (or validate) the collection in the store now so
    # that a ConflictError (dim mismatch) surfaces here, not after work.
    probe_dim = dimensions
    if probe_dim is None:
        cached = _dimensions.get(_dimensions_key(collection))
        if cached is not None and cached[0] > time.monotonic():
            probe_dim = cached[1]
    if probe_dim is None:
        probe_response = await embedder.embed(
            model=cfg.embedder.model,
            inputs=[TextPart(text="dimensionality probe")],
        )
        if not probe_response.embeddings:
            raise PrimerError(
                f"embedder returned no embedding for dimensionality probe "
                f"(collection {collection.id!r})"
            )
        probe_dim = len(probe_response.embeddings[0].vector)
        _dimensions[_dimensions_key(collection)] = (time.monotonic() + _DIMENSIONS_TTL_SECONDS, probe_dim)
    try:
        await store.create_collection(collection.id, dimensions=probe_dim)
    except ConflictError as exc:
        # The collection is already registered in the store with a different
        # dimension. Parse the stored dim from the ConflictError message
        # produced by all store backends ("dimensions=<N>" in the message).
        stored_dim = _parse_stored_dim(str(exc), fallback=0)
        raise DimensionMismatchError(
            f"Embedder output dimension ({probe_dim}) does not match the "
            f"vector store dimension ({stored_dim}) recorded for collection "
            f"{collection.id!r}. The collection was indexed with a different "
            f"embedding model. To fix: delete all documents from this "
            f"collection, then re-create it with the correct embedder, and "
            f"re-ingest the documents.",
            embedder_dim=probe_dim,
            collection_dim=stored_dim,
            collection_id=collection.id,
            cause=exc,
        ) from exc

    # A document whose chunks are exactly what is stored has nothing to do (the rule ``index_documents`` applies): no embedding, no write.
    # It must have been embedded by this collection's embedder too: after a model change the same text is stale (an explicit reindex never skips).
    fingerprint = embedder_fingerprint(collection)
    if chunks and not force and _is_current((await _stored_chunk_texts(store, collection.id, document.id)).get(document.id), chunks, fingerprint):
        return len(chunks), False

    # Embed FIRST, before touching the existing chunks. If the embedder
    # fails (transient error, missing key), we must not have already
    # deleted the document's old chunks: the replace below only runs once
    # every new vector is in hand, so a failure here leaves the prior
    # index intact and the document still searchable.
    #
    # Batch the chunk embeddings: each embed
    # call carries up to ``_EMBED_BATCH_SIZE`` chunks and returns one
    # embedding per input in input order, so the records line up with the
    # chunks one-to-one. This is behaviour-equivalent to the previous
    # per-chunk loop (same vector per chunk, same chunk_id == str(idx),
    # same order) but collapses N embedder round-trips into ceil(N / 32).
    # The dimensionality-mismatch PROBE above is untouched; only the main
    # chunk embedding is batched here.
    records: list[EmbeddingRecord] = []
    for batch_start in range(0, len(chunks), _EMBED_BATCH_SIZE):
        batch = chunks[batch_start : batch_start + _EMBED_BATCH_SIZE]
        response = await embedder.embed(
            model=cfg.embedder.model,
            inputs=[TextPart(text=chunk) for chunk in batch],
        )
        if len(response.embeddings) != len(batch):
            raise PrimerError(
                f"embedder returned {len(response.embeddings)} embeddings "
                f"for {len(batch)} chunk(s) of document {document.id!r}"
            )
        for offset, (chunk, emb) in enumerate(
            zip(batch, response.embeddings, strict=True)
        ):
            idx = batch_start + offset
            records.append(
                EmbeddingRecord(
                    collection_id=collection.id,
                    document_id=document.id,
                    chunk_id=str(idx),
                    text=chunk,
                    vector=list(emb.vector),
                    meta={"path": document.path, "embedder": fingerprint},
                )
            )

    # The body may have moved while the embedder worked (a peer wrote v2, or the document was deleted): re-read it. A changed body is embedded again
    # by the caller's loop; a deleted one leaves no chunks (KN-9).
    now = await content_store.get(document.id)
    if now != body:
        if now is None:
            try:
                await store.delete(collection.id, document.id)
            except PrimerError:
                pass
            return 0, False
        return 0, True

    # Now that embedding succeeded, atomically-ish replace the document's
    # chunks: drop the prior set, then upsert the new one. The vector store
    # exposes no native "replace by document id", so this is delete + put;
    # because it runs only after a successful embed there is no failure
    # window that leaves the document with zero chunks. Chunk ids are the
    # stable str(idx), so a shorter re-index could leave higher-index stale
    # rows behind without the delete -- hence the delete is still required.
    try:
        await store.delete(collection.id, document.id)
    except PrimerError:
        # Tolerate stores that raise on delete when the collection has no
        # prior rows (some backends signal an unregistered collection this
        # way). The probe's create_collection above already registered it.
        pass

    if not chunks:
        # An empty body produces no records: the delete above already
        # cleared any prior chunks, which is the intended replace-with-empty.
        return 0, False

    # Idempotent: the probe already registered the collection above.
    # Calling again is a no-op for all compliant backends.
    await store.create_collection(
        collection.id, dimensions=len(records[0].vector)
    )
    await _put_all(store, records)

    logger.info(
        "indexed document %s into collection %s (%d chunks)",
        document.id, collection.id, len(records),
    )
    return len(records), False


async def index_documents(
    *,
    documents,
    collection: Collection,
    provider_registry,
    semantic_search_registry,
    content_store: DocumentContentStore,
    storage_provider=None,
    force: bool = False,
) -> int:
    """Index many documents in one pass.

    Returns how many documents it actually (re)indexed, which is not the
    number passed in: see the skip rule below.

    Same contract as :func:`index_document`, batched. The per-document
    form makes one embedder round-trip per document plus a probe, which
    is fine for a single write and ruinous for a backfill: enabling
    search on the system collection meant several hundred calls, and
    the e2e lane hit its per-test ceiling re-bootstrapping five times.
    Chunks are batched ACROSS documents here, so the number of calls
    tracks total chunks rather than document count.

    Documents whose stored chunks already match what they would produce
    are skipped: a backfill re-run over unchanged content does no
    embedding at all. That is what makes re-enabling search cheap, and
    it is the difference between a bootstrap that costs a full re-index
    every time and one that costs only the drift. Documents that are
    absent from the index, or whose text has moved on, are re-embedded.

    A document's chunks are replaced as soon as ALL of its vectors are in hand (not after the whole pass), so a failure part-way leaves the prior
    vectors of the documents not reached intact and keeps the documents already done: the re-run embeds only the rest (KN-13). The pass also
    removes the chunks of every document the index holds that is not in ``documents`` (it is given the whole collection): a document deleted while
    its unindex failed, or while search was off, would otherwise stay searchable for ever (KN-8).
    """
    if collection.search is None:
        return 0
    await _refuse_unless_an_owner_may_use(storage_provider, collection)
    cfg = collection.search
    fingerprint = embedder_fingerprint(collection)
    from primer.knowledge.splitter import split_text

    embedder = await provider_registry.get_embedder(cfg.embedder.provider_id)
    store = await semantic_search_registry.get_store(
        cfg.vector_store_provider_id
    )

    # What the index already holds, read once for the whole pass. An
    # unregistered collection means "nothing", which is the first run.
    existing = await _stored_chunk_texts(store, collection.id)

    # (document, chunk_index, text) flattened across the documents that
    # actually need work.
    flat: list[tuple[str, int, str]] = []
    stale: list[str] = []
    bodies: dict[str, str | None] = {}
    expected: dict[str, int] = {}
    for doc in documents:
        body = await content_store.get(doc.id)
        bodies[doc.id] = body
        chunks = split_text(
            body or "",
            max_chars=cfg.chunking.max_chars,
            overlap=cfg.chunking.overlap,
        )
        if not force and _is_current(existing.get(doc.id, {}), chunks, fingerprint):
            continue
        stale.append(doc.id)
        expected[doc.id] = len(chunks)
        flat.extend((doc.id, idx, chunk) for idx, chunk in enumerate(chunks))

    # The chunks of documents that are no longer in the collection (KN-8).
    present = {doc.id for doc in documents}
    for gone in [doc_id for doc_id in existing if doc_id not in present]:
        async with _document_lock(collection.id, gone):
            try:
                await store.delete(collection.id, gone)
            except PrimerError:
                pass

    if not stale:
        logger.info(
            "collection %s already indexed; nothing to backfill", collection.id,
        )
        return 0

    dimensions = await probe_dimensions(
        collection=collection, provider_registry=provider_registry,
    )
    try:
        await store.create_collection(collection.id, dimensions=dimensions)
    except ConflictError as exc:
        stored_dim = _parse_stored_dim(str(exc), fallback=0)
        raise DimensionMismatchError(
            f"Embedder output dimension ({dimensions}) does not match the "
            f"vector store dimension ({stored_dim}) recorded for collection "
            f"{collection.id!r}. The collection was indexed with a different "
            f"embedding model. To fix: delete all documents from this "
            f"collection, then re-create it with the correct embedder, and "
            f"re-ingest the documents.",
            embedder_dim=dimensions,
            collection_dim=stored_dim,
            collection_id=collection.id,
            cause=exc,
        ) from exc

    # Paths for the record meta, keyed by id so the loop below need not
    # carry the Document objects around.
    paths = {doc.id: doc.path for doc in documents}

    pending: dict[str, list[EmbeddingRecord]] = {}
    flushed = 0

    async def flush(doc_id: str) -> None:
        """Replace one document's chunks now that all its vectors are in hand, unless its body moved on (its own write path indexes it)."""
        nonlocal flushed
        async with _document_lock(collection.id, doc_id):
            now = await content_store.get(doc_id)
            if now != bodies[doc_id]:
                if now is None:
                    try:
                        await store.delete(collection.id, doc_id)
                    except PrimerError:
                        pass
                return
            try:
                await store.delete(collection.id, doc_id)
            except PrimerError:
                pass
            if pending.get(doc_id):
                await _put_all(store, pending[doc_id])
            flushed += 1

    for doc_id in [d for d in stale if expected[d] == 0]:       # an empty body replaces the old chunks with nothing
        await flush(doc_id)
    total_chunks = 0
    for start in range(0, len(flat), _EMBED_BATCH_SIZE):
        batch = flat[start : start + _EMBED_BATCH_SIZE]
        response = await embedder.embed(
            model=cfg.embedder.model,
            inputs=[TextPart(text=chunk) for _, _, chunk in batch],
        )
        if len(response.embeddings) != len(batch):
            raise PrimerError(
                f"embedder returned {len(response.embeddings)} embeddings "
                f"for {len(batch)} chunk(s) of collection {collection.id!r}"
            )
        finished: list[str] = []
        for (doc_id, idx, chunk), emb in zip(
            batch, response.embeddings, strict=True
        ):
            pending.setdefault(doc_id, []).append(EmbeddingRecord(
                collection_id=collection.id,
                document_id=doc_id,
                chunk_id=str(idx),
                text=chunk,
                vector=list(emb.vector),
                meta={"path": paths.get(doc_id, ""), "embedder": fingerprint},
            ))
            total_chunks += 1
            if len(pending[doc_id]) == expected[doc_id]:
                finished.append(doc_id)
        for doc_id in finished:
            await flush(doc_id)

    logger.info(
        "indexed %d document(s) into collection %s (%d chunks)",
        flushed, collection.id, total_chunks,
    )
    return flushed


async def remove_document_index(
    *,
    document_id: str,
    collection: Collection,
    semantic_search_registry,
) -> None:
    """Delete every indexed chunk for a document. Best-effort, idempotent."""
    if collection.search is None:
        return
    store = await semantic_search_registry.get_store(
        collection.search.vector_store_provider_id
    )
    async with _document_lock(collection.id, document_id):
        try:
            await store.delete(collection.id, document_id)
        except PrimerError:
            pass


# ---------------------------------------------------------------------------
# Write-through hooks
# ---------------------------------------------------------------------------
#
# A document written into a collection with search enabled has to reach the
# vector store, whichever path wrote it. Three paths do: the REST document
# routes, the collections toolset an agent drives, and the startup pass that
# regenerates the system collection. Only the first wired these up, so an
# agent could write a document into a search-enabled collection and leave it
# unsearchable, and the system map went stale in the index the moment an
# entity changed.
#
# They live here, keyed off registries rather than a Request, so the two
# non-HTTP callers can use the same ones instead of growing their own.


def make_document_indexer(
    *, storage_provider, provider_registry, semantic_search_registry,
):
    """Best-effort ``(document, content) -> None`` index-on-write hook.

    A missing collection is a no-op and a dimension mismatch propagates
    (it is an operator-configuration error the caller turns into a 422);
    anything else is logged and swallowed, so a write still succeeds when
    the embedding backend is down. The document simply is not searchable
    until something indexes it again.
    """

    async def _indexer(*, document: Document, content: str) -> None:
        collection = await storage_provider.get_storage(Collection).get(
            document.collection_id
        )
        if collection is None:
            return
        try:
            await index_document(
                document=document,
                collection=collection,
                provider_registry=provider_registry,
                semantic_search_registry=semantic_search_registry,
                content_store=storage_provider.get_content_store(),
                storage_provider=storage_provider,
            )
        except DimensionMismatchError:
            raise
        except Exception:  # noqa: BLE001 - best-effort indexing
            logger.exception(
                "document %s: indexing failed; row persisted but not searchable",
                document.id,
            )

    return _indexer


def make_document_unindexer(*, storage_provider, semantic_search_registry):
    """Best-effort per-document vector cleanup for deletes."""

    async def _unindexer(*, document_id: str, collection_id: str) -> None:
        collection = await storage_provider.get_storage(Collection).get(
            collection_id
        )
        if collection is None:
            return
        try:
            await remove_document_index(
                document_id=document_id, collection=collection,
                semantic_search_registry=semantic_search_registry,
            )
        except Exception:  # noqa: BLE001 - best-effort cleanup
            logger.exception(
                "document %s: unindexing failed; chunks may linger", document_id,
            )

    return _unindexer


def make_document_path_rewriter(*, storage_provider, semantic_search_registry):
    """Best-effort chunk path-metadata rewrite after a move."""

    async def _rewriter(
        *, document_id: str, collection_id: str, new_path: str
    ) -> None:
        collection = await storage_provider.get_storage(Collection).get(
            collection_id
        )
        if collection is None:
            return
        try:
            await rewrite_document_path_meta(
                document_id=document_id, collection=collection,
                semantic_search_registry=semantic_search_registry,
                new_path=new_path,
            )
        except Exception:  # noqa: BLE001 - best-effort rewrite
            logger.exception(
                "document %s: path-meta rewrite failed; stale paths may "
                "linger in the index", document_id,
            )

    return _rewriter




async def rewrite_document_path_meta(
    *,
    document_id: str,
    collection: Collection,
    semantic_search_registry,
    new_path: str,
) -> None:
    """Rewrite each stored chunk's meta path after a move. Metadata only:
    vectors are reused verbatim (spec section 6), so no embedder runs."""
    if collection.search is None:
        return
    store = await semantic_search_registry.get_store(
        collection.search.vector_store_provider_id
    )
    try:
        records = await store.get(collection.id, document_id)
        for record in records:
            await store.put(record.model_copy(
                update={"meta": {**record.meta, "path": new_path}}
            ))
    except PrimerError:
        pass


