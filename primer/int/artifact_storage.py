"""Abstract interface for binary artifact storage.

An ``ArtifactStorage`` stores opaque media bytes (chat images / documents /
audio) under an autogenerated id and reads them back. It is the live
implementation behind an :class:`primer.model.provider.ArtifactStorageProvider`
row, resolved per-row by
:class:`primer.api.registries.artifact_storage_registry.ArtifactStorageRegistry`.

The default backend (``DB``) persists an :class:`primer.model.artifact.Artifact`
row through the platform StorageProvider, keeping media bytes out of the
``ChatMessage`` row. Alternate backends (filesystem, S3) implement the same
contract so callers never depend on where the bytes live.

Callers do not hold a backend directly. They call
``ArtifactStorageRegistry.get_default()``, which returns a routing store
(:class:`primer.artifact.routing.RoutingArtifactStorage`): it writes to the
active provider and finds an artifact again through the
:class:`primer.model.artifact.ArtifactLocation` record written for it. A
backend only has to say, with :attr:`ArtifactStorage.needs_location_record`,
whether the router must write that record.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import TYPE_CHECKING, ClassVar

if TYPE_CHECKING:
    from primer.model.provider import ArtifactStorageProvider


@dataclass(frozen=True)
class ArtifactBlob:
    """Bytes plus the metadata needed to forward them to a model or channel."""

    data: bytes
    mime_type: str
    filename: str | None = None


class ArtifactStorage(ABC):
    """Provider-agnostic put/get/delete for opaque media bytes."""

    #: True when an id this backend mints cannot be found again by the database fallback, so the routing store writes an
    #: :class:`~primer.model.artifact.ArtifactLocation` for it. The default is True, the safe side: a backend that forgets to say so gets records
    #: it may not need, never artifacts it cannot find. Only a backend that stores in the ``Artifact`` table (the database) sets it False.
    needs_location_record: ClassVar[bool] = True

    def serves(self, row: "ArtifactStorageProvider") -> bool:
        """True when this live store still writes where ``row`` says.

        A store is built from the provider row read when it was resolved and is cached. The routing store reads the row again after a put has
        written its record and asks the store: a store whose row now names another location (a root, bucket or prefix moved while the put was in
        flight, before any record made the move check refuse it) answers False, and the put removes its bytes and record and fails with a
        conflict. The default is True: a backend whose location cannot move (the database) has nothing to compare. A backend with a location
        compares it after the same normalisation it applies when it writes.
        """
        del row
        return True

    @abstractmethod
    async def initialize(self) -> None:
        """Open connections / resources. Idempotent."""

    @abstractmethod
    async def put(
        self, *, data: bytes, mime_type: str, filename: str | None = None,
    ) -> str:
        """Store ``data`` and return its autogenerated ``artifact_id``."""

    @abstractmethod
    async def get(self, artifact_id: str) -> ArtifactBlob | None:
        """Return the stored blob, or None when the id is unknown."""

    @abstractmethod
    async def delete(self, artifact_id: str) -> None:
        """Remove ``artifact_id``. No-op when it does not exist."""

    @abstractmethod
    async def aclose(self) -> None:
        """Release connections / resources. Idempotent."""


__all__ = ["ArtifactBlob", "ArtifactStorage"]
